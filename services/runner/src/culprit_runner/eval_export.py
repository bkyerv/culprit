"""Native ADK regression artifacts for a measured winning branch."""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import tempfile
import time
from pathlib import Path
from typing import Any

from culprit_core import Criterion, Event
from google.adk.evaluation.eval_case import EvalCase, IntermediateData, Invocation, SessionInput
from google.adk.evaluation.eval_rubrics import Rubric, RubricContent
from google.adk.evaluation.eval_set import EvalSet
from google.genai import types

ADK_EVAL_TIMEOUT_SECONDS = 120
ADK_EVAL_OUTPUT_LIMIT_BYTES = 256 * 1024


def _tool_trajectory(events: list[Event]) -> tuple[list[types.FunctionCall], list[types.FunctionResponse]]:
    calls: list[types.FunctionCall] = []
    responses: list[types.FunctionResponse] = []
    for event in events:
        content = event.payload.get("content") or {}
        for part in content.get("parts") or []:
            if function_call := part.get("function_call"):
                calls.append(types.FunctionCall.model_validate(function_call))
            if function_response := part.get("function_response"):
                responses.append(types.FunctionResponse.model_validate(function_response))
    return calls, responses


def build_evalset(
    *,
    evalset_id: str,
    run_id: str,
    branch_id: str,
    task: str,
    final_response: str,
    events: list[Event],
    criteria: list[Criterion],
) -> EvalSet:
    """Project a winning counterfactual into ADK's current native EvalSet schema."""

    tool_uses, tool_responses = _tool_trajectory(events)
    rubrics = [
        Rubric(
            rubric_id=criterion.criterion_id,
            rubric_content=RubricContent(text_property=str(criterion.config["rubric"])),
            type="FINAL_RESPONSE_QUALITY",
        )
        for criterion in criteria
        if criterion.grader == "rubric" and criterion.config.get("rubric")
    ]
    now = time.time()
    invocation = Invocation(
        invocation_id=f"{run_id}-{branch_id}",
        user_content=types.Content(
            role="user", parts=[types.Part.from_text(text=task)]
        ),
        final_response=types.Content(
            role="model", parts=[types.Part.from_text(text=final_response)]
        ),
        intermediate_data=IntermediateData(
            tool_uses=tool_uses,
            tool_responses=tool_responses,
        ),
        creation_timestamp=now,
    )
    return EvalSet(
        eval_set_id=evalset_id,
        name=f"Culprit winning path for {run_id}",
        description=(
            f"Measured counterfactual winner {branch_id}; derived from failed run {run_id}."
        ),
        eval_cases=[
            EvalCase(
                eval_id=f"winning-path-{branch_id}",
                conversation=[invocation],
                session_input=SessionInput(
                    app_name="culprit_subject", user_id="regression", state={}
                ),
                rubrics=rubrics or None,
                creation_timestamp=now,
            )
        ],
        creation_timestamp=now,
    )


def evalset_bytes(evalset: EvalSet) -> bytes:
    # Round-trip through ADK's own model before the artifact leaves the runner.
    payload = (evalset.model_dump_json(indent=2, by_alias=True) + "\n").encode()
    EvalSet.model_validate_json(payload)
    return payload


def render_pytest(evalset_filename: str) -> bytes:
    """Render a portable pytest using the requested AgentEvaluator entry point."""

    source = f'''"""Regression generated by Culprit from a measured winning path."""

import asyncio
import os
from pathlib import Path

from google.adk.evaluation.agent_evaluator import AgentEvaluator


def test_culprit_winning_path() -> None:
    evalset_path = Path(__file__).with_name({evalset_filename!r})
    os.environ["CULPRIT_EVALSET_PATH"] = str(evalset_path)
    agent_module = os.environ.get("CULPRIT_AGENT_MODULE", "culprit_runner.eval_replay")
    asyncio.run(
        AgentEvaluator.evaluate(
            agent_module=agent_module,
            eval_dataset_file_path_or_dir=str(evalset_path),
            num_runs=1,
            print_detailed_results=False,
        )
    )
'''
    return source.encode("utf-8")


def validate_evalset_with_adk(evalset: EvalSet) -> dict[str, Any]:
    """Run the installed `adk eval` CLI, not merely a Pydantic parse."""

    executable = shutil.which("adk")
    if executable is None:
        raise RuntimeError("installed google-adk package did not provide the adk executable")
    final_response = "".join(
        part.text or ""
        for part in (evalset.eval_cases[0].conversation or [])[0].final_response.parts
    )
    with tempfile.TemporaryDirectory(prefix="culprit-adk-eval-") as temp_name:
        root = Path(temp_name)
        agent_dir = root / "validation_agent"
        agent_dir.mkdir()
        (agent_dir / "__init__.py").write_text("from . import agent\n", encoding="utf-8")
        agent_source = f'''from google.adk.agents import Agent
from google.genai import types

EXPECTED_RESPONSE = {final_response!r}

async def fixed_response(callback_context):
    return types.Content(
        role="model", parts=[types.Part.from_text(text=EXPECTED_RESPONSE)]
    )

root_agent = Agent(
    name="culprit_evalset_validator",
    model="gemini-3.7-flash",
    before_agent_callback=fixed_response,
)
'''
        (agent_dir / "agent.py").write_text(agent_source, encoding="utf-8")
        evalset_path = root / f"{evalset.eval_set_id}.evalset.json"
        evalset_path.write_bytes(evalset_bytes(evalset))
        config_path = root / "test_config.json"
        config_path.write_text(
            json.dumps({"criteria": {"response_match_score": 1.0}}), encoding="utf-8"
        )
        argv = [
            executable,
            "eval",
            str(agent_dir),
            str(evalset_path),
            "--config_file_path",
            str(config_path),
        ]
        started = time.perf_counter()
        completed = subprocess.run(
            argv,
            check=False,
            capture_output=True,
            timeout=ADK_EVAL_TIMEOUT_SECONDS,
            env={**os.environ, "GOOGLE_CLOUD_LOCATION": "global"},
        )
        stdout = completed.stdout[:ADK_EVAL_OUTPUT_LIMIT_BYTES].decode(errors="replace")
        stderr = completed.stderr[:ADK_EVAL_OUTPUT_LIMIT_BYTES].decode(errors="replace")
        accepted = all(
            (
                completed.returncode == 0,
                "Eval Run Summary" in stdout,
                evalset.eval_set_id in stdout,
                re.search(r"Tests failed:\s*0\b", stdout) is not None,
            )
        )
        result = {
            "accepted": accepted,
            "argv": ["adk", *argv[1:]],
            "exit_code": completed.returncode,
            "stdout": stdout,
            "stderr": stderr,
            "duration_ms": round((time.perf_counter() - started) * 1000, 3),
            "schema": "google.adk.evaluation.eval_set.EvalSet",
        }
        if not accepted:
            raise RuntimeError(f"adk eval did not accept the exported evalset: {result}")
        return result
